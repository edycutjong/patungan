"""Writes src/fonts/: the one Anybody instance the app draws (weight 850, width 75%), cut from @fontsource-variable/anybody.

The app's CSS sets Anybody only as `font: 850 …; font-stretch: 75%`, so the full variable font (both axes, ~57 KB for
latin) is fetched to draw one style. A static instance of that style is the same outlines in ~13 KB. Same subsets and
unicode-ranges as the fontsource CSS. Re-run after bumping the package:  python3 scripts/instance-anybody.py
Needs fonttools + brotli (pip install fonttools brotli). The landing page and /judge keep their own copies in public/fonts.
"""
import re
import shutil
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WEB = Path(__file__).resolve().parent.parent
PKG = WEB / 'node_modules/@fontsource-variable/anybody'
OUT = WEB / 'src/fonts'
WGHT, WDTH = 850, 75

OUT.mkdir(exist_ok=True)
faces = []
for subset, ranges in re.findall(r'/\* anybody-([a-z-]+)-wdth-normal \*/.*?unicode-range: ([^;]+);', (PKG / 'wdth.css').read_text(), re.S):
    name = f'anybody-{subset}-{WGHT}-{WDTH}.woff2'
    font = instantiateVariableFont(TTFont(PKG / f'files/anybody-{subset}-wdth-normal.woff2'), {'wght': WGHT, 'wdth': WDTH})
    font.flavor = 'woff2'
    font.save(OUT / name)
    faces.append(
        f"""/* anybody-{subset}, {WGHT} at {WDTH}% width */
@font-face {{
  font-family: 'Anybody Variable';
  font-style: normal;
  font-display: swap;
  font-weight: {WGHT};
  font-stretch: {WDTH}%;
  src: url(./{name}) format('woff2');
  unicode-range: {ranges};
}}
"""
    )
header = '/* Generated by scripts/instance-anybody.py from @fontsource-variable/anybody (SIL OFL 1.1, see OFL.txt). Do not edit. */\n'
(OUT / 'anybody.css').write_text(header + '\n'.join(faces))
shutil.copy(PKG / 'LICENSE', OUT / 'OFL.txt')
print('\n'.join(f'{p.name} {p.stat().st_size} B' for p in sorted(OUT.glob('*.woff2'))))
